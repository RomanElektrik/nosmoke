export function getChapter(id: string): BookChapter | undefined {
  return CHAPTERS.find((c) => c.id === id);
}

/** Глава целиком: тело на нужном языке с фолбэком на RU (EN пишем следующим заходом). */
export function chapterBody(ch: BookChapter, ru: boolean): BookBlock[] {
  return ru ? ch.bodyRu : (ch.bodyEn ?? ch.bodyRu);
}

/** Следующая глава по порядку (для кнопки «дальше» в ридере). null на последней. */
export function nextChapter(id: string): BookChapter | null {
  const i = CHAPTERS.findIndex((c) => c.id === id);
  return i >= 0 && i < CHAPTERS.length - 1 ? CHAPTERS[i + 1] : null;
}

/** Сколько глав прочитано (по карте bookProgress: chapterId → ms). Интро не считаем «главой». */
export function readCount(progress: Record<string, number> | undefined): number {
  if (!progress) return 0;
  return CHAPTERS.filter((c) => c.number > 0 && progress[c.id]).length;
}

